function check(name,cond){ if(cond){pass++;} else {fail++;console.log('FAIL:',name);} }
check('SM1 larger inline map',shell.includes('min-height:clamp(620px,70vh,760px)'));
check('SM1 near-full-screen map popout',shell.includes('#mapPopout .popout-window')&&shell.includes('calc(100vw - 16px)'));
check('SM1 collapsible layout',render.includes('mapPopApplyLayout')&&render.includes('toggleMapPopOnly'));
check('SM1 resize observer',render.includes('map3dResizeObserver')&&render.includes('ResizeObserver'));
check('SM2 camera presets',render.includes('function map3dPreset'));
check('SM2 fit helper',render.includes('function map3dFitVisibleObjects'));
check('SM2 smooth transitions',render.includes('function map3dStartTransition'));
check('SM2 zoom controls',render.includes('function map3dZoom'));
check('SM3 selection halo',render.includes('selectionHalo'));
check('SM3 distant markers',render.includes('Distant markers:'));
check('SM3 label collision pass',render.includes('label tiers')&&render.includes('occupied'));
check('SM3 labels stay screen-sized',render.includes('map3dWorldUnitsForPixels')&&render.includes('labelAspect'));
check('SM3 marker labels do not duplicate sprites',render.includes('markerVisible[id]'));
check('SM3 orbit modes',render.includes('function map3dSetOrbitMode'));
check('SM3 hover emphasis',render.includes('hoveredId'));
check('SM4 map quality tiers',render.includes('const MAP3D_QUALITY='));
check('SM4 deterministic star layers',render.includes('function map3dMakeStarLayer'));
