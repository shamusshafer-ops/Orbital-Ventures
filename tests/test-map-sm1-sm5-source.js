check('SM5 strategic',render.includes("strategic:{icon:"));
check('single scene architecture retained',render.includes('function remountMap3D')&&render.includes('appendChild(map3d.dom)'));
check('diagnostics retained',render.includes('window.ovMapDiag'));
console.log(`${pass}/${pass+fail} checks passed`);
process.exit(fail?1:0);
